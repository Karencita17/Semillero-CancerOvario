#Librerias para trabajar con imagenes, números y matrices, hacer gráficos y mostrar imagenes
import cv2
import numpy as np
import matplotlib.pyplot as plt
from google.colab.patches import cv2_imshow
from google.colab import files

# El usuario selecciona la imagen desde su PC
archivo = files.upload()

# Obtener el nombre del archivo seleccionado
nombre = next(iter(archivo))

from google.colab import drive
drive.mount('/content/drive')

imagen = cv2.imread(nombre) #Leer imagen

if imagen.shape[0] != 100 and imagen.shape[1] != 100:
  imagen_redimensionada = cv2.resize(imagen, (100, 100))
else:
  imagen_redimensionada = imagen

imagen_RGB = cv2.cvtColor(imagen_redimensionada, cv2.COLOR_BGR2RGB)

imagen_gris = cv2.cvtColor(imagen_RGB, cv2.COLOR_BGR2GRAY)

# Guardar la imagen modificada
cv2.imwrite("imagen_modificada.jpg", imagen_gris)

# Descargar automáticamente
files.download("imagen_modificada.jpg")

alto, ancho = imagen_redimensionada.shape[:2]
centro = (ancho // 2, alto // 2)
angulo = 45
matriz_rotacion = cv2.getRotationMatrix2D(centro, angulo, 0.7)
imagen_rotada = cv2.warpAffine(imagen_redimensionada, matriz_rotacion, (ancho, alto))
cv2.imwrite("imagen_rotada_45.jpg", imagen_rotada)
files.download("imagen_rotada_45.jpg")

