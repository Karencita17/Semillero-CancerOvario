# Importamos las librerias a usar
import numpy as np
import cv2
import matplotlib.pyplot as plt
from google.colab.patches import cv2_imshow
import urllib.request
from skimage import util
from matplotlib.patches import Rectangle

# Importamos la imagen
imagen = cv2.imread('/CancerOvario.png')

# Cambiamos de BGR --> RGB
Imagen_RGB = cv2.cvtColor(imagen, cv2.COLOR_BGR2RGB)
plt.imshow(Imagen_RGB)
plt.show()

# Cambiamos imagen de color a escala de grises
Imagen_gris = cv2.cvtColor(imagen, cv2.COLOR_BGR2GRAY)
plt.imshow(Imagen_gris, cmap='gray')
plt.show()

# Verificamos dimensiones y tipo de la imagen a color
print('Dimensiones color', imagen.shape)
print('tipo color', imagen.dtype)

# Verificamos dimensiones y tipo de la imagen  en gris
print('Dimensiones en escala de grises', Imagen_gris.shape)
print('tipo gris', Imagen_gris.dtype)

# Agregamos filtro Gaussiano
Imagen_gaussiana = util.random_noise(Imagen_gris, mode='gaussian')
plt.imshow(Imagen_gaussiana, cmap='gray')
plt.show()

# Agregamos filtro Sal y Pimienta.
sal_pimienta = util.random_noise(Imagen_gris, mode='s&p')
plt.imshow(sal_pimienta, cmap='gray')
plt.show()

# Mostramos las 3 imagenes en un gráfico
fig, axes = plt.subplots(1, 3, figsize=(12, 5))

# Imagen gris
axes[0].imshow(Imagen_gris, cmap='gray')
axes[0].set_title('Imagen original')

# Imagen con filtro Gaussiano
axes[1].imshow(Imagen_gaussiana, cmap='gray')
axes[1].set_title('Imagen con filtro Gaussiano')

#Imagen con filtro Sal y Pimienta
axes[2].imshow(sal_pimienta, cmap='gray')
axes[2].set_title('Imagen con filtro Sal y Pimienta')
plt.show()