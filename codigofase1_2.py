#Librerias para trabajar con imagenes, números y matrices, hacer gráficos y mostrar imagenes
import cv2
import numpy as np
import matplotlib.pyplot as plt
from google.colab.patches import cv2_imshow
from google.colab import files

# El usuario selecciona la imagen desde su PC
archivo = files.upload()

# Obtener el nombre del archivo seleccionado
nombre = next(iter(archivo))

from google.colab import drive
drive.mount('/content/drive')

imagen = cv2.imread(nombre) #Leer imagen

# Trabajamos siempre con imagenes 100x100
if imagen.shape[0] != 100 or imagen.shape[1] != 100:
  imagen_redimensionada = cv2.resize(imagen, (100, 100))
else:
  imagen_redimensionada = imagen

# Cambiamos de BGR --> RGB
imagen_RGB = cv2.cvtColor(imagen_redimensionada, cv2.COLOR_BGR2RGB)

# Cambiamos a escala de grises
imagen_gris = cv2.cvtColor(imagen_RGB, cv2.COLOR_BGR2GRAY)

# Guardar la imagen modificada
cv2.imwrite("imagen_modificada.jpg", imagen_gris)

# Descargar automáticamente
files.download("imagen_modificada.jpg")

# Sacamos el centro de la imagen
alto, ancho = imagen_redimensionada.shape[:2]
centro = (ancho // 2, alto // 2)

# Rotamos imagen 45 grados
angulo = 45
matriz_rotacion = cv2.getRotationMatrix2D(centro, angulo, 0.7)
imagen_rotada_45 = cv2.warpAffine(imagen_RGB, matriz_rotacion, (ancho, alto))
cv2.imwrite("imagen_rotada_45.jpg", imagen_rotada_45)
files.download("imagen_rotada_45.jpg")

# Rotamos imagen 60 grados
angulo = 60
matriz_rotacion = cv2.getRotationMatrix2D(centro, angulo, 0.7)
imagen_rotada_60 = cv2.warpAffine(imagen_RGB, matriz_rotacion, (ancho, alto))
cv2.imwrite("imagen_rotada_60.jpg", imagen_rotada_60)
files.download("imagen_rotada_60.jpg")

# Rotamos imagen 90 grados
angulo = 90
matriz_rotacion = cv2.getRotationMatrix2D(centro, angulo, 0.7)
imagen_rotada_90 = cv2.warpAffine(imagen_RGB, matriz_rotacion, (ancho, alto))
cv2.imwrite("imagen_rotada_90.jpg", imagen_rotada_90)
files.download("imagen_rotada_90.jpg")

# Rotamos imagen 180 grados
angulo = 180
matriz_rotacion = cv2.getRotationMatrix2D(centro, angulo, 0.7)
imagen_rotada_180 = cv2.warpAffine(imagen_RGB, matriz_rotacion, (ancho, alto))
cv2.imwrite("imagen_rotada_180.jpg", imagen_rotada_180)
files.download("imagen_rotada_180.jpg")

# Mostramos las imagenes en una gráfica
fig, axes =plt.subplots (1,5, figsize=(15,15))

axes[0].imshow(imagen_RGB)
axes[0].set_title("Imagen original")
axes[0].axis("off")

axes[1].imshow(imagen_rotada_45)
axes[1].set_title("Imagen rotada 45 grados")
axes[1].axis("off")

axes[2].imshow(imagen_rotada_60)
axes[2].set_title("Imagen rotada 60 grados")
axes[2].axis("off")

axes[3].imshow(imagen_rotada_90)
axes[3].set_title("Imagen rotada 90 grados")
axes[3].axis("off")

axes[4].imshow(imagen_rotada_180)
axes[4].set_title("Imagen rotada 180 grados")
axes[4].axis("off")

plt.show()